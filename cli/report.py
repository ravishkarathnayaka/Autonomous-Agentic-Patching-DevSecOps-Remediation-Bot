"""
CLI Security Report Generator
Compiles DevSecOps scan findings into executive Markdown and JSON audit reports.
"""

from typing import List, Dict, Any, Optional
from datetime import datetime, timezone
import json


def generate_executive_report(
    findings: List[Dict[str, Any]],
    repository: str = "target_repo",
    output_format: str = "markdown"
) -> str:
    """
    Generate an executive security posture report from a list of findings.

    Args:
        findings: List of finding dictionaries with keys: severity, cwe, file, line, description
        repository: Name or path of the repository
        output_format: 'markdown' or 'json'
    """
    counts = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0, "INFO": 0}
    cwe_map: Dict[str, int] = {}

    for f in findings:
        sev = str(f.get("severity", "LOW")).upper()
        counts[sev] = counts.get(sev, 0) + 1
        cwe = f.get("cwe", "UNKNOWN")
        cwe_map[cwe] = cwe_map.get(cwe, 0) + 1

    total = len(findings)
    crit_high = counts.get("CRITICAL", 0) + counts.get("HIGH", 0)
    risk_posture = "POOR" if crit_high > 3 else ("CONCERNING" if crit_high > 0 else "HEALTHY")

    if output_format.lower() == "json":
        report_data = {
            "repository": repository,
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "risk_posture": risk_posture,
            "total_findings": total,
            "severity_distribution": counts,
            "top_cwes": dict(sorted(cwe_map.items(), key=lambda item: item[1], reverse=True)[:5]),
            "findings": findings
        }
        return json.dumps(report_data, indent=2)

    # Markdown format
    lines = [
        f"# Executive DevSecOps Security Posture Report",
        f"",
        f"- **Repository:** `{repository}`",
        f"- **Timestamp:** `{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%SZ')}`",
        f"- **Risk Posture:** **{risk_posture}**",
        f"- **Total Security Findings:** **{total}**",
        f"",
        f"## 1. Severity Distribution",
        f"",
        f"| Severity | Count | SLA Requirement |",
        f"| :--- | :--- | :--- |",
        f"| 🚨 Critical | {counts.get('CRITICAL', 0)} | < 24 Hours |",
        f"| ⚠️ High | {counts.get('HIGH', 0)} | < 72 Hours |",
        f"| 🟡 Medium | {counts.get('MEDIUM', 0)} | < 14 Days |",
        f"| ℹ️ Low | {counts.get('LOW', 0)} | < 30 Days |",
        f"",
        f"## 2. Common Weakness Enumeration (CWE) Breakdown",
        f""
    ]

    sorted_cwes = sorted(cwe_map.items(), key=lambda item: item[1], reverse=True)[:5]
    for cwe, c_count in sorted_cwes:
        lines.append(f"- **{cwe}**: {c_count} finding(s)")

    lines.extend([
        f"",
        f"## 3. Recommended Remediation Actions",
        f"",
        f"1. Trigger autonomous patching agent on all Critical and High findings.",
        f"2. Execute regression test suites inside isolated Docker sandbox.",
        f"3. Enforce branch protection rules on main to require CI verification.",
        f"",
        f"---",
        f"*Generated by Autonomous Agentic Patching & DevSecOps Remediation Bot*"
    ])

    return "\n".join(lines)

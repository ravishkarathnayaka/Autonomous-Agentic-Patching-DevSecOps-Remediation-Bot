"""CLI tool to generate Atlassian Jira DevSecOps issue payload."""

import json
from pathlib import Path
from typing import Optional
import click

from agent_engine.state import Finding, FindingType, SeverityLevel
from agent_engine.tools.jira_formatter import JiraTicketFormatter


@click.command(name="jira-issue", help="Format a vulnerability finding into Jira REST API issue payload.")
@click.option(
    "--project",
    "-p",
    "project_key",
    default="SEC",
    help="Jira project key (e.g. SEC).",
)
@click.option(
    "--scanner",
    "-s",
    "scanner",
    default="semgrep",
    help="Name of security scanner.",
)
@click.option(
    "--rule-id",
    "-r",
    "rule_id",
    required=True,
    help="Security rule or vulnerability ID.",
)
@click.option(
    "--title",
    "-t",
    "title",
    required=True,
    help="Summary or title of the finding.",
)
@click.option(
    "--severity",
    "-v",
    "severity",
    type=click.Choice(["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"], case_sensitive=False),
    default="HIGH",
    help="Normalized severity level.",
)
@click.option(
    "--file",
    "-f",
    "file_path",
    default="src/app.py",
    help="Relative path to affected source file.",
)
@click.option(
    "--output",
    "-o",
    "output_file",
    type=click.Path(dir_okay=False, writable=True),
    help="Output JSON file path. Defaults to stdout.",
)
def jira_issue(
    project_key: str,
    scanner: str,
    rule_id: str,
    title: str,
    severity: str,
    file_path: str,
    output_file: Optional[str],
) -> None:
    """Format Jira issue JSON."""
    finding = Finding(
        id="jira-finding-01",
        scanner=scanner,
        finding_type=FindingType.SAST,
        rule_id=rule_id,
        title=title,
        description=f"Automated vulnerability detection for {rule_id} in {file_path}",
        severity=SeverityLevel(severity.upper()),
        file_path=file_path,
    )

    payload = JiraTicketFormatter.format_issue_payload(
        finding=finding,
        project_key=project_key,
        patch_summary="Patch generated by Autonomous DevSecOps Bot.",
    )

    formatted = json.dumps(payload, indent=2)
    if output_file:
        Path(output_file).parent.mkdir(parents=True, exist_ok=True)
        with open(output_file, "w", encoding="utf-8") as f:
            f.write(formatted)
        click.echo(f"Jira issue payload written to {output_file}")
    else:
        click.echo(formatted)


if __name__ == "__main__":
    jira_issue()
